/**
 * Renders contracts/lib/mch/index_vectors.test.ak: the shared hand-written
 * vectors plus seeded random cases, with expected values computed by this
 * package. If the Aiken and TypeScript index implementations ever disagree,
 * `aiken check` fails. test/aiken-vectors.test.ts fails if the file is stale.
 */
import type { Basket } from '../src/basket.ts';
import { computeIndex, type PriceMap } from '../src/index-math.ts';
import { METAL_IDS, type MetalId } from '../src/metals.ts';
import vectors from '../test/vectors.json' with { type: 'json' };

interface Case {
  name: string;
  components: Array<{ metal: MetalId; weightPpm: number; basePriceMicro: bigint }>;
  prices: bigint[];
  expected: bigint;
}

function mulberry32(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function handWritten(): Case[] {
  return vectors.cases.map((v) => {
    const components = v.components.map((c) => ({
      metal: c.metal as MetalId,
      weightPpm: c.weightPpm,
      basePriceMicro: BigInt(c.basePriceMicro),
    }));
    const pricesMicro = v.pricesMicro as Record<string, string>;
    return {
      name: v.name,
      components,
      prices: components.map((c) => BigInt(pricesMicro[c.metal]!)),
      expected: BigInt(v.expectedIndexMicro),
    };
  });
}

function randomCases(count: number, seed: number): Case[] {
  const rand = mulberry32(seed);
  const cases: Case[] = [];
  for (let i = 0; i < count; i++) {
    const n = 1 + Math.floor(rand() * METAL_IDS.length);
    const metals = METAL_IDS.slice(0, n);
    const cuts = Array.from({ length: n - 1 }, () => 1 + Math.floor(rand() * 999_998)).sort(
      (a, b) => a - b,
    );
    const edges = [0, ...cuts, 1_000_000];
    const weights = metals.map((_, j) => edges[j + 1]! - edges[j]!);
    if (weights.some((w) => w <= 0)) {
      i--;
      continue;
    }
    const components = metals.map((metal, j) => ({
      metal,
      weightPpm: weights[j]!,
      basePriceMicro: BigInt(1 + Math.floor(rand() * 60_000_000_000)),
    }));
    const prices = components.map((c) =>
      BigInt(1 + Math.floor(Number(c.basePriceMicro) * (0.02 + rand() * 6))),
    );
    const basket: Basket = {
      name: 'r',
      version: 1,
      baseDate: '2026-10-13',
      isDemo: true,
      components,
    };
    const priceMap: PriceMap = Object.fromEntries(components.map((c, j) => [c.metal, prices[j]!]));
    cases.push({
      name: `random case ${i + 1}`,
      components,
      prices,
      expected: computeIndex(basket, priceMap).indexMicro,
    });
  }
  return cases;
}

const RANDOM_CASES = 150;
const RANDOM_SEED = 20261013;

export function renderAikenVectors(): string {
  const all = [...handWritten(), ...randomCases(RANDOM_CASES, RANDOM_SEED)];
  const tests = all.map((c, i) => {
    const comps = c.components
      .map(
        (x) =>
          `      Component { metal: "${x.metal}", weight_ppm: ${x.weightPpm}, base_price: ${x.basePriceMicro} },`,
      )
      .join('\n');
    const label = `vector_${String(i + 1).padStart(3, '0')}`;
    return [
      `// ${c.name}`,
      `test ${label}() {`,
      `  compute_index(`,
      `    [`,
      comps,
      `    ],`,
      `    [${c.prices.join(', ')}],`,
      `  ) == ${c.expected}`,
      `}`,
    ].join('\n');
  });
  return [
    '// GENERATED by packages/index-core/scripts/gen-aiken-vectors.ts. Do not edit.',
    '// Expected values come from the TypeScript implementation; if this file',
    '// fails `aiken check`, the two index implementations disagree.',
    '',
    'use mch/index_math.{compute_index}',
    'use mch/types.{Component}',
    '',
    tests.join('\n\n'),
    '',
  ].join('\n');
}
